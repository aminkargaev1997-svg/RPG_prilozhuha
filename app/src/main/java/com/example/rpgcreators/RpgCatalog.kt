        "Мистическое фэнтези" -> "Мифология"
        "Техника и фантастика" -> when(entry.name) {
            "Киборг", "Андроид", "Синтетик" -> "Киберпанк"
            "Мутант" -> "Постапокалипсис"
            else -> "Космическая фантастика"
        }
        "Необычные народы" -> "Классическое фэнтези"
        else -> entry.group
    }
    private fun originalProfessionGenre(entry: CatalogEntry): String = when(entry.group) {
        "Технологии и будущее" -> "Киберпанк"
        else -> "Классическое фэнтези"
    }
    private fun normaliseMarker(entry: CatalogEntry): CatalogEntry {
        val category = when {
            entry.group.startsWith("Противники") -> "Противники"
            entry.group == "Места" -> "Локации"
            entry.group == "Находки" -> "Объекты"
            entry.group == "Боевая тактика" -> "Тактика"
            entry.markerType == "NPC" || entry.markerType == "Союзник" -> "NPC"
            else -> "События"
        }
        val genre = when {
            "технологии" in entry.group -> "Киберпанк"
            "нежить" in entry.group -> "Тёмное фэнтези"
            else -> "Классическое фэнтези"
        }
        return entry.copy(group = category, genre = genre)
    }

    /** Сохраняем старые варианты и расширяем их; дубликаты названий не показываем. */
    val races: List<CatalogEntry> = (
        originalRaces.map { it.copy(group = originalRaceGenre(it), genre = originalRaceGenre(it)) } +
            RpgCatalogData.races
    ).distinctBy { it.name.trim().lowercase() }

    val professions: List<CatalogEntry> = (
        originalProfessions.map { it.copy(group = originalProfessionGenre(it), genre = originalProfessionGenre(it)) } +
            RpgCatalogData.professions
    ).distinctBy { it.name.trim().lowercase() }

    /** Маркеры одинакового названия в разных жанрах остаются независимыми шаблонами. */
    val markerPresets: List<CatalogEntry> = (
        originalMarkerPresets.map(::normaliseMarker) + RpgCatalogData.markerPresets
    ).distinctBy { it.name.trim().lowercase() to it.genre }
}
